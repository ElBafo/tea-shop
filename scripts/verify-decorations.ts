import assert from 'node:assert/strict';
import {UPGRADES, emptyShop, shopComplete, bakeryUnlocked, spentStars, placeOf} from '../src/shop/upgrades';
import {sanitizeShop, canPlace} from '../src/shop/grid';
const core=UPGRADES.filter(x=>!x.optional);
const extras=UPGRADES.filter(x=>x.optional);
assert.equal(core.length,8);
assert.equal(extras.length,9);
const shop=emptyShop();shop.owned=core.map(x=>x.id);
assert.equal(shopComplete(shop),true);
assert.equal(bakeryUnlocked(shop),true);
assert.equal(spentStars(shop),26);
shop.owned=UPGRADES.map(x=>x.id);
const clean=sanitizeShop(shop);
for(const item of UPGRADES.filter(d=>!clean.stored?.includes(d.id))) assert.equal(canPlace(item.id,placeOf(clean,item.id),clean),true,`${item.id} fits the completed room`);
assert.equal(spentStars(clean),122);
assert.ok(spentStars(clean)>38*3, "optional collections create meaningful choices");
assert.equal(canPlace('art',{x:4,z:0,rot:0,wall:'back'},clean),false,'window stays visible');
assert.equal(canPlace('clock',{x:0,z:0,rot:0,wall:'back'},clean),false,'shelves remain clear');
console.log('Optional completion, catalogue cost, and decoration placement checks passed.');
