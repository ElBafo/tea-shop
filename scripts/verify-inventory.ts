import assert from 'node:assert/strict';
import { emptyShop, DECORATIONS, spentStars, canPurchaseCopy, shopComplete, isStored, placeOf } from '../src/shop/upgrades';
import { storeItem, placeItem, cloneInventory } from '../src/shop/inventory';
import { sanitizeShop, canPlace } from '../src/shop/grid';
import { LEVEL_COUNT } from '../src/game/types';
const legacy = {owned:['lamp'] as const, style:{lamp:2}, place:{lamp:{x:2,z:3,rot:0}}, finaleSeen:false};
const old = sanitizeShop({...legacy, owned:[...legacy.owned]});
assert.deepEqual(old.stored, []);
assert.equal(old.style.lamp,2);
assert.equal(canPurchaseCopy(emptyShop(),'lamp:2'),false);
assert.equal(canPurchaseCopy(old,'lamp:2'),true);
const two = sanitizeShop({...old, owned:['lamp','lamp:2'],style:{lamp:2,'lamp:2':1}});
assert.ok(canPlace('lamp:2',placeOf(two,'lamp:2'),two));
const stored = storeItem(two,'lamp')!;
assert.equal(spentStars(stored),8);
assert.equal(isStored(two,'lamp'),false,'operation does not mutate existing state');
assert.equal(canPlace('lamp:2',placeOf(two,'lamp'),stored),true,'stored item frees its cell');
assert.equal(stored.style['lamp:2'],1);
assert.deepEqual(placeItem(stored,'lamp')!.place,two.place);
assert.equal(storeItem(stored,'lamp'),null);
assert.equal(storeItem({...emptyShop(),owned:['paint']},'paint'),null);
const clone=cloneInventory(stored);clone.place.lamp!.x=0;assert.equal(stored.place.lamp!.x,2);
const all=sanitizeShop({...emptyShop(),owned:DECORATIONS.map(d=>d.id)});
assert.equal(spentStars(all),88);
assert.equal(LEVEL_COUNT*3,90);
assert.equal(shopComplete(all),true);
const packed=storeItem(all,'counter')!;
assert.equal(shopComplete(packed),true,'storage does not revoke completion');
assert.equal(spentStars(packed),88);
for(const id of all.owned)if(!isStored(all,id))assert.ok(canPlace(id,placeOf(all,id),all),id);
const wall=sanitizeShop({...emptyShop(),owned:['shelves','sign','art','clock','art:2'],place:{sign:{x:1,z:0,wall:'left',rot:1},art:{x:4,z:0,wall:'left',rot:1},clock:{x:1,z:0,wall:'back',rot:0},'art:2':{x:5,z:0,wall:'left',rot:1}},stored:['shelves']});
assert.equal(placeItem(wall,'shelves'),null,'fragmented wall keeps paid shelves in storage');
assert.ok(placeItem(storeItem(wall,'clock')!,'shelves'),'storing clock frees the back wall');
console.log('Inventory migration, independent copies, free storage, collision and 88/90 star budget passed.');
